package IntroTopics;

public class ArithematicOperators {
    public static void main(String[] args){
        int number1=12;
        int number2=5;
        System.out.println(number1-number2);
        System.out.println(number1+number2);
        System.out.println(number1*number2);
        System.out.println(number1/number2);
        System.out.println(number1%number2);
    }
}
