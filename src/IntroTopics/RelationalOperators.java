package IntroTopics;

public class RelationalOperators {
    public static void main(String[] args){
        //relational operators are used to check relationship between two operators
        int a = 10;
        int b = 20;
        System.out.println(a==b);
        System.out.println(a!=b);
        System.out.println(a>=b);
        System.out.println(a<=b);
        System.out.println(a>b);
        System.out.println(a<b);
        //relational operators are used in the decision making process

    }
}
